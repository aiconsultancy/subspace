WORKFLOWS = SCRIPTS.parent / ".github/workflows"


class StargatePinCheckTests(unittest.TestCase):
    """Each release branch gets the Stargate pin check the way it gets the lockfiles check; the check needs
    the network, so it stays out of the offline gates."""

    def test_the_release_branches_get_the_pin_check(self) -> None:
        refresh = (SCRIPTS / "release-lockfiles.sh").read_text()
        self.assertIn('gh workflow run stargate-pin.yml --repo "$repo" --ref "$1"', refresh)
        workflow = (WORKFLOWS / "stargate-pin.yml").read_text()
        for line in ("  pull_request:\n", "  workflow_dispatch:\n", "permissions: {}\n",
                     "      contents: read\n", "        run: python3 scripts/stargate-pin.py --check\n",
                     "github.ref_name != 'release-please--branches--main--components--subspace-framework'"):
            self.assertIn(line, workflow)
        self.assertNotIn("write", workflow)
        self.assertNotIn("continue-on-error", workflow)

    def test_the_offline_gates_do_not_ask_github(self) -> None:
        makefile = (SCRIPTS.parent / "Makefile").read_text()
        recipe = makefile.split("\nrelease-check:", 1)[1].split("\n\n", 1)[0]
        hooks = (SCRIPTS.parent / "prek.toml").read_text()
        for text in (recipe, hooks):
            self.assertNotIn("stargate-pin.py --check", text)
            self.assertNotIn("stargate-pin.py --json", text)

    def test_every_action_is_pinned_to_a_commit(self) -> None:
        for workflow in sorted(WORKFLOWS.glob("*.yml")):
            for line in workflow.read_text().splitlines():
                if line.strip().startswith(("uses:", "- uses:")):
                    with self.subTest(workflow=workflow.name, line=line):
                        self.assertRegex(line, r"uses: [\w.-]+/[\w./-]+@[0-9a-f]{40} # v\d")


STARGATE_API = "https://api.github.com/repos/aiconsultancy/stargate"
OLD, NEW, NEWER = "a" * 40, "b" * 40, "c" * 40
RUNTIME = f'''STARGATE_REPO = "https://github.com/aiconsultancy/stargate.git"
# The pin.
STARGATE_RELEASE = "v0.43.0"
STARGATE_REF = "{OLD}"
SUBSPACE_REPO = "https://github.com/aiconsultancy/subspace.git"
'''


class FakeStargate:
    """GitHub's API for Stargate. `releases` are (tag, commit, kind), newest first, where kind is
    lightweight, annotated, draft or prerelease; the first lightweight or annotated one is the latest."""

    def __init__(self, releases, failure: Exception | None = None):
        self.requests = []
        self.failure = failure
        published = [release for release in releases if release[2] in ("lightweight", "annotated")]
        self.routes = {
            "/releases/latest": {"tag_name": published[0][0], "html_url": f"https://example.com/{published[0][0]}"},
            "/releases?per_page=100": [
                {"tag_name": tag, "html_url": f"https://example.com/{tag}",
                 "draft": kind == "draft", "prerelease": kind == "prerelease"} for tag, _, kind in releases],
        }
        for tag, commit, kind in releases:
            if kind == "annotated":
                self.routes[f"/git/ref/tags/{tag}"] = {"object": {"type": "tag", "sha": "d" * 40}}
                self.routes[f"/git/tags/{'d' * 40}"] = {"object": {"type": "commit", "sha": commit}}
            else:
                self.routes[f"/git/ref/tags/{tag}"] = {"object": {"type": "commit", "sha": commit}}

    def __call__(self, request, timeout):
        self.requests.append(request)
        if self.failure:
            raise self.failure
        path = request.full_url.removeprefix(STARGATE_API)
        if path not in self.routes:
            raise urllib.error.HTTPError(request.full_url, 404, "Not Found", {}, None)
        return io.BytesIO(json.dumps(self.routes[path]).encode())


class StargatePinTests(unittest.TestCase):
    TODAY = datetime.date(2026, 11, 22)

    def setUp(self) -> None:
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.runtime = Path(directory.name) / "runtime.py"
        self.runtime.write_text(RUNTIME)
        self.hold = Path(directory.name) / "stargate-hold.json"
        for patcher in (mock.patch.object(PIN, "RUNTIME", self.runtime), mock.patch.object(PIN, "HOLD", self.hold),
                        mock.patch.dict("os.environ", {"GITHUB_ACTIONS": ""})):
            patcher.start()
            self.addCleanup(patcher.stop)

    def run_pin(self, fake, *argv, token=None):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = PIN.main(list(argv), PIN.GitHub(token, opener=fake), self.TODAY)
        return code, out.getvalue(), err.getvalue()

    def behind(self, kind="lightweight"):
        return FakeStargate([("v0.45.0", NEWER, "prerelease"), ("v0.44.1", NEW, kind),
                             ("v0.44.0", "e" * 40, "lightweight"), ("v0.43.1", "f" * 40, "draft"),
                             ("v0.43.0", OLD, "lightweight"), ("v0.42.0", "9" * 40, "lightweight")])

    def test_a_current_pin_passes(self) -> None:
        fake = FakeStargate([("v0.43.0", OLD, "lightweight")])
        code, out, _ = self.run_pin(fake, "--check")
        self.assertEqual(code, 0)
        self.assertIn(f"pinned {OLD}, which is v0.43.0; the latest release is v0.43.0 at {OLD}", out)
        # Only GitHub's API, only for Stargate, and no token unless one is set.
        for request in fake.requests:
            self.assertTrue(request.full_url.startswith(STARGATE_API + "/"), request.full_url)
            self.assertIsNone(request.get_header("Authorization"))

    def test_a_pin_behind_the_latest_release_fails_only_the_check(self) -> None:
        fake = self.behind()
        code, out, _ = self.run_pin(fake, "--check", token="fixture-token")
        self.assertEqual(code, 1)
        self.assertIn(f"pinned {OLD}, which is v0.43.0; the latest release is v0.44.1 at {NEW}", out)
        self.assertEqual(fake.requests[0].get_header("Authorization"), "Bearer fixture-token")
        self.assertEqual(self.run_pin(self.behind())[0], 0)

    def test_an_annotated_tag_is_followed_to_its_commit(self) -> None:
        code, out, _ = self.run_pin(self.behind("annotated"), "--check")
        self.assertEqual(code, 1)
        self.assertIn(f"the latest release is v0.44.1 at {NEW}", out)
        self.assertNotIn("d" * 40, out)

    def test_a_label_that_does_not_name_the_pin_is_not_a_release(self) -> None:
        self.runtime.write_text(RUNTIME.replace(OLD, "1" * 40))
        code, out, _ = self.run_pin(FakeStargate([("v0.43.0", OLD, "lightweight")]), "--check")
        self.assertEqual(code, 1)
        self.assertIn(f"pinned {'1' * 40}, which is not a release (labelled v0.43.0, whose tag is at", out)

    def test_the_json_lists_each_published_release_since_the_pin(self) -> None:
        code, out, _ = self.run_pin(self.behind(), "--json")
        self.assertEqual(code, 0)
        result = json.loads(out)
        self.assertEqual(result["state"], "behind")
        self.assertEqual([release["tag"] for release in result["between"]], ["v0.44.0", "v0.44.1"])
        self.assertEqual(result["latest"], {"tag": "v0.44.1", "url": "https://example.com/v0.44.1", "sha": NEW})

    def test_update_moves_only_the_pin(self) -> None:
        code, out, _ = self.run_pin(self.behind(), "--update", "--expect", "v0.44.1")
        self.assertEqual(code, 0, out)
        self.assertEqual(self.runtime.read_text(), RUNTIME.replace('"v0.43.0"', '"v0.44.1"').replace(OLD, NEW))
        self.assertEqual(self.run_pin(self.behind(), "--check")[0], 0)

    def test_update_refuses_another_release_than_expected(self) -> None:
        code, _, err = self.run_pin(self.behind(), "--update", "--expect", "v0.44.0")
        self.assertEqual(code, 2)
        self.assertIn("the latest release is v0.44.1, not v0.44.0", err)
        self.assertEqual(self.runtime.read_text(), RUNTIME)

    def test_a_pin_not_assigned_exactly_once_is_refused(self) -> None:
        for text in (RUNTIME.replace('STARGATE_RELEASE = "v0.43.0"\n', ""),
                     RUNTIME + f'STARGATE_REF = "{OLD}"\n', RUNTIME.replace(OLD, "main")):
            with self.subTest(text=text), self.assertRaises(PIN.Invalid):
                PIN.read_pin(text)

    def write_hold(self, **changes) -> None:
        hold = {"pinned": "v0.43.0", "holding": "v0.44.1",
                "reason": "v0.44.1 renames the crew plugin's options.", "until": "2026-12-31", **changes}
        self.hold.write_text(json.dumps(hold))

    def test_a_hold_passes_with_its_reason_as_a_warning(self) -> None:
        self.write_hold()
        code, out, _ = self.run_pin(self.behind(), "--check")
        self.assertEqual(code, 0)
        self.assertIn("HELD", out)
        self.assertIn("renames the crew plugin's options", out)
        with mock.patch.dict("os.environ", {"GITHUB_ACTIONS": "true", "GITHUB_STEP_SUMMARY": ""}):
            _, out, _ = self.run_pin(self.behind(), "--check")
        self.assertIn("::warning title=Stargate pin::", out)

    def test_a_hold_ends_with_a_newer_release_its_date_or_another_pin(self) -> None:
        for changes, note in (({"holding": "v0.44.0"}, "covers v0.44.0 only"),
                              ({"until": "2026-11-21"}, "lapsed after 2026-11-21"),
                              ({"pinned": "v0.42.0"}, "which is not the pin")):
            with self.subTest(changes=changes):
                self.write_hold(**changes)
                code, out, _ = self.run_pin(self.behind(), "--check")
                self.assertEqual(code, 1)
                self.assertIn(note, out)

    def test_a_malformed_hold_is_refused(self) -> None:
        for changes in ({"reason": ""}, {"until": "soon"}, {"holding": "v0.43.0"}, {"extra": "key"}):
            with self.subTest(changes=changes):
                self.write_hold(**changes)
                code, _, err = self.run_pin(self.behind(), "--check")
                self.assertEqual(code, 2)
                self.assertIn("stargate-hold.json", err)

    def test_an_unreachable_api_and_an_api_error_fail_distinguishably(self) -> None:
        unreachable = FakeStargate([("v0.43.0", OLD, "lightweight")], urllib.error.URLError("no route to host"))
        code, _, err = self.run_pin(unreachable, "--check")
        self.assertEqual(code, 3)
        self.assertIn("cannot reach GitHub's API", err)
        limited = urllib.error.HTTPError(STARGATE_API, 403, "Forbidden", {"x-ratelimit-remaining": "0"}, None)
        code, _, err = self.run_pin(FakeStargate([("v0.43.0", OLD, "lightweight")], limited), "--check")
        self.assertEqual(code, 4)
        self.assertIn("answered 403 Forbidden", err)
        self.assertIn("set GH_TOKEN", err)

    def test_the_pull_request_says_what_to_check(self) -> None:
        result = json.loads(self.run_pin(self.behind(), "--json")[1])
        self.assertEqual(PIN.pr_title(result), "build(installer): move Stargate from v0.43.0 to v0.44.1")
        body = PIN.pr_body(result, "| policy_test.py | passed |", ["docs/teams.md"], None)
        for text in ("[v0.44.0](https://example.com/v0.44.0)", "[v0.44.1](https://example.com/v0.44.1)",
                     f"`{OLD}`", f"`{NEW}`", "| policy_test.py | passed |", "`docs/teams.md`",
                     "Generated configuration keys", "Service and path names", "crew plugin's options",
                     "CORS origins", "releases.tsv", "Docs links that name the pin", "on a VM",
                     "never merges anything", "add a hold"):
            self.assertIn(text, body)
        self.assertNotIn("v0.43.1", body)
        self.assertNotIn("v0.45.0", body)

    def test_the_repository_pin_and_hold_parse(self) -> None:
        pin = PIN.read_pin((SCRIPTS.parent / "subspace-installer/lib/runtime.py").read_text())
        self.assertIsNotNone(PIN.version(pin["release"]))
        hold = SCRIPTS.parent / "subspace-installer/stargate-hold.json"
        PIN.read_hold(hold.read_text() if hold.exists() else None)


class ConfigTests(unittest.TestCase):
    def setUp(self) -> None:
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        (self.root / "lib").mkdir()
        (self.root / "app").mkdir()
        (self.root / "lib/Cargo.toml").write_text(
            '[workspace.package]\nversion = "0.1.0"\n\n[workspace.dependencies]\n'
            '# x-release-please-start-version\n'
            'lib-core = { path = "core", version = "=0.1.0" }\n'
            '# x-release-please-end\nserde = "1.0.0"\n')
        (self.root / "app/Cargo.toml").write_text(
            '[workspace.package]\nversion = "0.8.0"\n\n[workspace.dependencies]\n'
            'lib = { path = "../lib", version = "0.1.0" }\n')
        self.config = {
            "separate-pull-requests": True, "bump-minor-pre-major": True,
            "bump-patch-for-minor-pre-major": False,
            "packages": {
                "lib": {"extra-files": [
                    {"type": "toml", "path": "Cargo.toml", "jsonpath": "$.workspace.package.version"},
                    {"type": "generic", "path": "Cargo.toml"},
                    {"type": "toml", "path": "/app/Cargo.toml",
                     "jsonpath": "$.workspace.dependencies['lib'].version"},
                ]},
                "app": {"extra-files": [
                    {"type": "toml", "path": "Cargo.toml", "jsonpath": "$.workspace.package.version"},
                ]},
            },
        }
        self.write({"lib": "0.1.0", "app": "0.8.0"})

    def write(self, manifest: dict) -> None:
        (self.root / "release-please-config.json").write_text(json.dumps(self.config))
        (self.root / ".release-please-manifest.json").write_text(json.dumps(manifest))

    def errors(self) -> list[str]:
        return CONFIG.errors(self.root, [self.root / "lib/Cargo.toml", self.root / "app/Cargo.toml"])

    def test_a_consistent_fixture_passes(self) -> None:
        self.assertEqual(self.errors(), [])

    def test_a_manifest_version_that_differs_from_cargo_fails(self) -> None:
        self.write({"lib": "0.2.0", "app": "0.8.0"})
        self.assertTrue(any("not at the manifest's 0.2.0" in error for error in self.errors()))

    def test_a_third_party_line_inside_a_block_fails(self) -> None:
        manifest = self.root / "lib/Cargo.toml"
        manifest.write_text(manifest.read_text().replace("# x-release-please-end\nserde", "serde"))
        manifest.write_text(manifest.read_text() + "# x-release-please-end\n")
        self.assertTrue(any("not a pin" in error for error in self.errors()))

    def test_an_annotation_in_a_file_another_package_owns_fails(self) -> None:
        manifest = self.root / "app/Cargo.toml"
        manifest.write_text(manifest.read_text().replace(
            'version = "0.1.0" }', 'version = "0.1.0" } # x-release-please-version'))
        self.assertTrue(any("no package's generic extra file" in error for error in self.errors()))

    def test_a_missing_path_or_wrong_rule_fails(self) -> None:
        self.config["packages"]["app"]["extra-files"].append(
            {"type": "toml", "path": "missing/Cargo.toml", "jsonpath": "$.package.version"})
        self.config["bump-patch-for-minor-pre-major"] = True
        self.write({"lib": "0.1.0", "app": "0.8.0"})
        found = self.errors()
        self.assertTrue(any("does not exist" in error for error in found))
        self.assertTrue(any("bump-patch-for-minor-pre-major" in error for error in found))

    def test_the_repository_configuration_passes(self) -> None:
        result = subprocess.run([sys.executable, str(SCRIPTS / "check-release-config.py")],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)


