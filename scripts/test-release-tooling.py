class SyncTests(unittest.TestCase):
    VERSIONS = {"subspace": "0.9.0", "subspace-core": "0.2.0", "serde": "9.9.9", "libghostty-vt": "9.9.9"}

    def test_only_local_workspace_packages_move(self) -> None:
        text, changes = SYNC.sync(LOCKFILE, self.VERSIONS)
        self.assertEqual(changes, ["subspace 0.8.0 -> 0.9.0", "subspace-core 0.1.0 -> 0.2.0"])
        expected = LOCKFILE.replace('"subspace"\nversion = "0.8.0"', '"subspace"\nversion = "0.9.0"')
        expected = expected.replace('"subspace-core"\nversion = "0.1.0"', '"subspace-core"\nversion = "0.2.0"')
        self.assertEqual(text, expected)
        # Registry and git packages and unknown path packages keep their versions.
        self.assertIn('name = "serde"\nversion = "0.1.0"', text)
        self.assertIn('name = "libghostty-vt"\nversion = "0.2.2"', text)
        self.assertIn('name = "markdown"\nversion = "1.0.0"', text)

    def test_a_synced_lockfile_is_left_alone(self) -> None:
        text, _ = SYNC.sync(LOCKFILE, self.VERSIONS)
        self.assertEqual(SYNC.sync(text, self.VERSIONS), (text, []))

    def test_the_repository_lockfiles_match_the_manifests(self) -> None:
        result = subprocess.run([sys.executable, str(SCRIPTS / "sync-lockfiles.py"), "--check"],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_a_name_with_two_versions_is_refused(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for workspace, version in zip(SYNC.WORKSPACES, ("0.1.0", "0.2.0", "0.2.0", "0.2.0")):
                (root / workspace / "src").mkdir(parents=True)
                (root / workspace / "src/lib.rs").write_text("")
                (root / workspace / "Cargo.toml").write_text(
                    f'[package]\nname = "same"\nversion = "{version}"\nedition = "2024"\n\n[workspace]\n')
            with self.assertRaises(ValueError):
                SYNC.local_versions(root)


