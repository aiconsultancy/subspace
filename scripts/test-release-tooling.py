"""The lockfile sync and the Release Please configuration check, on fixtures and on this repository."""

import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent


def load(name: str):
    spec = importlib.util.spec_from_file_location(name.replace("-", "_"), SCRIPTS / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


SYNC = load("sync-lockfiles")
CONFIG = load("check-release-config")

LOCKFILE = '''# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "libghostty-vt"
version = "0.2.2"
source = "git+https://github.com/example/ghostty?rev=3425025e#3425025e"

[[package]]
name = "markdown"
version = "1.0.0"

[[package]]
name = "serde"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0000"

[[package]]
name = "subspace"
version = "0.8.0"
dependencies = [
 "subspace-core",
]

[[package]]
name = "subspace-core"
version = "0.1.0"
'''


class SyncTests(unittest.TestCase):
    VERSIONS = {"subspace": "0.9.0", "subspace-core": "0.2.0", "serde": "9.9.9", "libghostty-vt": "9.9.9"}

    def test_only_local_workspace_packages_move(self) -> None:
        text, changes = SYNC.sync(LOCKFILE, self.VERSIONS)
        self.assertEqual(changes, ["subspace 0.8.0 -> 0.9.0", "subspace-core 0.1.0 -> 0.2.0"])
        expected = LOCKFILE.replace('"subspace"\nversion = "0.8.0"', '"subspace"\nversion = "0.9.0"')
        expected = expected.replace('"subspace-core"\nversion = "0.1.0"', '"subspace-core"\nversion = "0.2.0"')
        self.assertEqual(text, expected)
        # Registry and git packages and unknown path packages keep their versions.
        self.assertIn('name = "serde"\nversion = "0.1.0"', text)
        self.assertIn('name = "libghostty-vt"\nversion = "0.2.2"', text)
        self.assertIn('name = "markdown"\nversion = "1.0.0"', text)

    def test_a_synced_lockfile_is_left_alone(self) -> None:
        text, _ = SYNC.sync(LOCKFILE, self.VERSIONS)
        self.assertEqual(SYNC.sync(text, self.VERSIONS), (text, []))

    def test_the_repository_lockfiles_match_the_manifests(self) -> None:
        result = subprocess.run([sys.executable, str(SCRIPTS / "sync-lockfiles.py"), "--check"],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_a_name_with_two_versions_is_refused(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for workspace, version in zip(SYNC.WORKSPACES, ("0.1.0", "0.2.0", "0.2.0", "0.2.0")):
                (root / workspace / "src").mkdir(parents=True)
                (root / workspace / "src/lib.rs").write_text("")
                (root / workspace / "Cargo.toml").write_text(
                    f'[package]\nname = "same"\nversion = "{version}"\nedition = "2024"\n\n[workspace]\n')
            with self.assertRaises(ValueError):
                SYNC.local_versions(root)


class LockfilesCheckTests(unittest.TestCase):
    """The workflow release-lockfiles.sh starts on each release branch, which
    has no pull_request run, exists, can be started, and runs the check."""

    def test_the_release_branches_get_the_lockfiles_check(self) -> None:
        refresh = (SCRIPTS / "release-lockfiles.sh").read_text()
        self.assertIn('gh workflow run lockfiles.yml --repo "$repo" --ref "$1"', refresh)
        workflow = (SCRIPTS.parent / ".github/workflows/lockfiles.yml").read_text()
        for line in ("  pull_request:\n", "  workflow_dispatch:\n",
                     "        run: python3 scripts/sync-lockfiles.py --check\n"):
            self.assertIn(line, workflow)
        release = (SCRIPTS.parent / ".github/workflows/release.yml").read_text()
        self.assertRegex(release, r"actions: write\b")


class ConfigTests(unittest.TestCase):
    def setUp(self) -> None:
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        (self.root / "lib").mkdir()
        (self.root / "app").mkdir()
        (self.root / "lib/Cargo.toml").write_text(
            '[workspace.package]\nversion = "0.1.0"\n\n[workspace.dependencies]\n'
            '# x-release-please-start-version\n'
            'lib-core = { path = "core", version = "=0.1.0" }\n'
            '# x-release-please-end\nserde = "1.0.0"\n')
        (self.root / "app/Cargo.toml").write_text(
            '[workspace.package]\nversion = "0.8.0"\n\n[workspace.dependencies]\n'
            'lib = { path = "../lib", version = "0.1.0" }\n')
        self.config = {
            "separate-pull-requests": True, "bump-minor-pre-major": True,
            "bump-patch-for-minor-pre-major": False,
            "packages": {
                "lib": {"extra-files": [
                    {"type": "toml", "path": "Cargo.toml", "jsonpath": "$.workspace.package.version"},
                    {"type": "generic", "path": "Cargo.toml"},
                    {"type": "toml", "path": "/app/Cargo.toml",
                     "jsonpath": "$.workspace.dependencies['lib'].version"},
                ]},
                "app": {"extra-files": [
                    {"type": "toml", "path": "Cargo.toml", "jsonpath": "$.workspace.package.version"},
                ]},
            },
        }
        self.write({"lib": "0.1.0", "app": "0.8.0"})

    def write(self, manifest: dict) -> None:
        (self.root / "release-please-config.json").write_text(json.dumps(self.config))
        (self.root / ".release-please-manifest.json").write_text(json.dumps(manifest))

    def errors(self) -> list[str]:
        return CONFIG.errors(self.root, [self.root / "lib/Cargo.toml", self.root / "app/Cargo.toml"])

    def test_a_consistent_fixture_passes(self) -> None:
        self.assertEqual(self.errors(), [])

    def test_a_manifest_version_that_differs_from_cargo_fails(self) -> None:
        self.write({"lib": "0.2.0", "app": "0.8.0"})
        self.assertTrue(any("not at the manifest's 0.2.0" in error for error in self.errors()))

    def test_a_third_party_line_inside_a_block_fails(self) -> None:
        manifest = self.root / "lib/Cargo.toml"
        manifest.write_text(manifest.read_text().replace("# x-release-please-end\nserde", "serde"))
        manifest.write_text(manifest.read_text() + "# x-release-please-end\n")
        self.assertTrue(any("not a pin" in error for error in self.errors()))

    def test_an_annotation_in_a_file_another_package_owns_fails(self) -> None:
        manifest = self.root / "app/Cargo.toml"
        manifest.write_text(manifest.read_text().replace(
            'version = "0.1.0" }', 'version = "0.1.0" } # x-release-please-version'))
        self.assertTrue(any("no package's generic extra file" in error for error in self.errors()))

    def test_a_missing_path_or_wrong_rule_fails(self) -> None:
        self.config["packages"]["app"]["extra-files"].append(
            {"type": "toml", "path": "missing/Cargo.toml", "jsonpath": "$.package.version"})
        self.config["bump-patch-for-minor-pre-major"] = True
        self.write({"lib": "0.1.0", "app": "0.8.0"})
        found = self.errors()
        self.assertTrue(any("does not exist" in error for error in found))
        self.assertTrue(any("bump-patch-for-minor-pre-major" in error for error in found))

    def test_the_repository_configuration_passes(self) -> None:
        result = subprocess.run([sys.executable, str(SCRIPTS / "check-release-config.py")],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()
